-- 認証ポリシーを置くDB, SCHEMAを作成する
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS FROSTY_FRIDAY;
CREATE SCHEMA IF NOT EXISTS FROSTY_FRIDAY.POLICY;
CREATE WORKSPACE IF NOT EXISTS FROSTY_FRIDAY.PUBLIC.FROSTY_FRIDAY_WS;

-- SERVICE USERを作成する
USE ROLE ACCOUNTADMIN;
CREATE USER SERVICE_SNOWFLAKE_CLI TYPE = 'SERVICE';
GRANT ROLE SYSADMIN TO USER SERVICE_SNOWFLAKE_CLI;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SYSADMIN;

-- 認証ポリシーを作成する
USE ROLE ACCOUNTADMIN;
CREATE AUTHENTICATION POLICY FROSTY_FRIDAY.POLICY.SNOWFLAKE_CLI_ONLY
    AUTHENTICATION_METHODS = ('KEYPAIR')
    CLIENT_TYPES = ('SNOWFLAKE_CLI');

-- 認証ポリシーを設定する
ALTER USER SERVICE_SNOWFLAKE_CLI
  SET AUTHENTICATION POLICY FROSTY_FRIDAY.POLICY.SNOWFLAKE_CLI_ONLY;

-- 公開鍵を設定する
-- 名前付き秘密鍵
ALTER USER SERVICE_SNOWFLAKE_CLI ADD KEY PAIR FROSTY_FRIDAY_KEY
PUBLIC_KEY = 'M-----------B';

-- フィンガープリントを確認する
SHOW USER KEY PAIRS FOR USER SERVICE_SNOWFLAKE_CLI ->>
SELECT "fingerprint" FROM $1;

-- CLIでフィンガープリントを確認する


-- REPORTED_CLIENT_TYPEがSNOWFLAKE_CLIになっていることを確認する
SELECT * EXCLUDE (CLIENT_IP, EVENT_TIMESTAMP) FROM SNOWFLAKE.ACCOUNT_USAGE.LOGIN_HISTORY WHERE USER_NAME = 'SERVICE_SNOWFLAKE_CLI' ORDER BY EVENT_TIMESTAMP DESC;

